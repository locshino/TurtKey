pub fn key_code_to_char(code: u16, caps: bool) -> Option<char> {
    let ch = match code {
        KEY_A => if caps { 'A' } else { 'a' },
        KEY_B => if caps { 'B' } else { 'b' },
        KEY_C => if caps { 'C' } else { 'c' },
        KEY_D => if caps { 'D' } else { 'd' },
        KEY_E => if caps { 'E' } else { 'e' },
        KEY_F => if caps { 'F' } else { 'f' },
        KEY_G => if caps { 'G' } else { 'g' },
        KEY_H => if caps { 'H' } else { 'h' },
        KEY_I => if caps { 'I' } else { 'i' },
        KEY_J => if caps { 'J' } else { 'j' },
        KEY_K => if caps { 'K' } else { 'k' },
        KEY_L => if caps { 'L' } else { 'l' },
        KEY_M => if caps { 'M' } else { 'm' },
        KEY_N => if caps { 'N' } else { 'n' },
        KEY_O => if caps { 'O' } else { 'o' },
        KEY_P => if caps { 'P' } else { 'p' },
        KEY_Q => if caps { 'Q' } else { 'q' },
        KEY_R => if caps { 'R' } else { 'r' },
        KEY_S => if caps { 'S' } else { 's' },
        KEY_T => if caps { 'T' } else { 't' },
        KEY_U => if caps { 'U' } else { 'u' },
        KEY_V => if caps { 'V' } else { 'v' },
        KEY_W => if caps { 'W' } else { 'w' },
        KEY_X => if caps { 'X' } else { 'x' },
        KEY_Y => if caps { 'Y' } else { 'y' },
        KEY_Z => if caps { 'Z' } else { 'z' },
        KEY_1 => if caps { '!' } else { '1' },
        KEY_2 => if caps { '@' } else { '2' },
        KEY_3 => if caps { '#' } else { '3' },
        KEY_4 => if caps { '$' } else { '4' },
        KEY_5 => if caps { '%' } else { '5' },
        KEY_6 => if caps { '^' } else { '6' },
        KEY_7 => if caps { '&' } else { '7' },
        KEY_8 => if caps { '*' } else { '8' },
        KEY_9 => if caps { '(' } else { '9' },
        KEY_0 => if caps { ')' } else { '0' },
        KEY_BACKQUOTE => if caps { '~' } else { '`' },
        KEY_MINUS => if caps { '_' } else { '-' },
        KEY_EQUALS => if caps { '+' } else { '=' },
        KEY_LEFT_BRACKET => if caps { '{' } else { '[' },
        KEY_RIGHT_BRACKET => if caps { '}' } else { ']' },
        KEY_BACK_SLASH => if caps { '|' } else { '\\' },
        KEY_SEMICOLON => if caps { ':' } else { ';' },
        KEY_QUOTE => if caps { '"' } else { '\'' },
        KEY_COMMA => if caps { '<' } else { ',' },
        KEY_DOT => if caps { '>' } else { '.' },
        KEY_SLASH => if caps { '?' } else { '/' },
        KEY_SPACE => ' ',
        KEY_ENTER => '\n',
        KEY_TAB => '\t',
        _ => return None,
    };
    Some(ch)
}
